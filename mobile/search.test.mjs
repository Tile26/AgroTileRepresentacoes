import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source = readFileSync(new URL('./search.js',import.meta.url),'utf8');
const {searchEntries} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const clients = Array.from({length:250},(_,index) => ({id:index + 1,name:'Cliente ' + (250-index)}));
clients.push({id:999,name:'João Ávila',legalName:'Comercial Ávila',document:'123.456.789-00',phone:'(41) 9 9722-6198',city:'São José',state:'PR'});
assert.equal(searchEntries(clients,'').length,251);
assert.equal(searchEntries(clients,'')[0].name,'Cliente 1');
assert.equal(clients[0].name,'Cliente 250');
assert.deepEqual(searchEntries(clients,'joao sao').map(c => c.id),[999]);
assert.deepEqual(searchEntries(clients,'12345678900').map(c => c.id),[999]);
assert.deepEqual(searchEntries(clients,'41997226198').map(c => c.id),[999]);
assert.equal(searchEntries(clients,'sem resultado').length,0);
const products = Array.from({length:150},(_,index) => ({id:index,name:'Produto ' + index,categoryName:index % 2 ? 'Chapéus' : 'Erva-mate'}));
assert.equal(searchEntries(products,'chapeus').length,75);
assert.equal(searchEntries(products,'produto 149')[0].id,149);
assert.deepEqual(searchEntries([{id:null,name:'Todos'},{id:0,name:'Zero'}],'zero').map(p => p.id),[0]);
assert.deepEqual(searchEntries([{id:2,name:'B'},{id:1,name:'A'}],'',false).map(c => c.id),[2,1]);
console.log('Busca verificada com 251 clientes e 150 produtos, acentos, documentos, telefone e ordenação.');
